// ---------- spaced repetition per line ----------
const KEY = 'ct_openings_v1';
const DAY = 86400000;
const GAPS = [0, 1, 3, 7, 14, 30]; // days until the next review, by level

export function lineProgress(openingKey, lineId) {
  const all = store.get(KEY) || {};
  return all[`${openingKey}/${lineId}`] || { level: 0, due: 0, ok: 0, total: 0 };
}

export function recordLine(openingKey, lineId, ok) {
  const all = store.get(KEY) || {};
  const k = `${openingKey}/${lineId}`;
  const p = all[k] || { level: 0, due: 0, ok: 0, total: 0 };
  p.total++;
  if (ok) { p.ok++; p.level = Math.min(GAPS.length - 1, p.level + 1); } else p.level = Math.max(0, p.level - 1);
  p.due = Date.now() + GAPS[p.level] * DAY;
  all[k] = p;
  store.set(KEY, all);
  window.dispatchEvent(new Event('ct-progress'));
  return p;
}

export function lineStatus(p) {
  if (!p.total) return { label: 'חדש', cls: 'new' };
  if (p.due <= Date.now()) return { label: 'לחזרה היום', cls: 'due' };
  if (p.level >= 4) return { label: 'שולט', cls: 'master' };
  return { label: 'בלמידה', cls: 'learning' };
}
