const last = {};

export function quip(kind) {
  const list = QUIPS[kind];
  if (!list || !list.length) return '';
  let i = Math.floor(Math.random() * list.length);
  if (list.length > 1 && i === last[kind]) i = (i + 1) % list.length;
  last[kind] = i;
  return list[i];
}

// sometimes (not every time, so it stays funny)
export function maybeQuip(kind, chance = 0.5) {
  return Math.random() < chance ? quip(kind) : '';
}
